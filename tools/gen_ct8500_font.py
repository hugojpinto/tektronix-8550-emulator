"""Write emu/src/host/ct8500_font.inc from tools/ct8500_font.py, so the GUI draws the
same glyphs as the screenshots (Tek 308 ROM upper case + matching lower case; the
CT8500 character ROM itself has never been dumped).
usage: tools/gen_ct8500_font.py [OUTPUT]"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ct8500_font import glyph
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'emu', 'src', 'host', 'ct8500_font.inc')
with open(out, 'w') as f:
    f.write('// SPDX-License-Identifier: GPL-2.0-or-later\n// Copyright (C) 2026 Hugo José Pinto <hugo.pinto@gmail.com>\n')
    f.write('// Generated by tools/gen_ct8500_font.py -- do not edit.\n')
    f.write('// CT8500 glyphs 20h-7Fh: 8 rows of 5 dots, bit 4 = leftmost (approximation, see ct8500_font.py)\n')
    for c in range(0x20, 0x80):
        rows = glyph(c) if c != 0x7f else [0] * 8
        f.write('{ ' + ', '.join(f'0x{r:02x}' for r in rows) + ' },' + (f'   // {chr(c)!r}' if c < 0x7f else '   // DEL') + '\n')
print(out)
