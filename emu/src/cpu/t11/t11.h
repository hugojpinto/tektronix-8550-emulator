	// The bus the CPU sees. Byte addresses, 16-bit address space.
	struct bus_interface {
		virtual ~bus_interface() = default;
		// set 'nxm' to true when nothing answers (Q-bus timeout -> trap 4)
		virtual u16 read16(offs_t addr, bool &nxm) = 0;
		virtual void write16(offs_t addr, u16 data, bool &nxm) = 0;
		virtual void write8(offs_t addr, u8 data, bool &nxm) = 0;
		// interrupt acknowledge: return vector of highest-priority requester, or -1
		virtual int iack() = 0;
		virtual void bus_reset() {}          // RESET instruction (BINIT)
	};

	enum { CP0_LINE = 0, CP1_LINE, CP2_LINE, CP3_LINE, VEC_LINE, PF_LINE, HLT_LINE };
	static constexpr int EVENT_LINE = CP2_LINE;  // BEVNT -> vector 100
	static constexpr u8 BUS_ERROR = 8;

	explicit t11_device(bus_interface &bus);

	void reset(u16 start_pc, u16 start_psw = 0340);
	int  run(int cycles);                // returns cycles actually used
	void set_input(int line, int state);

	// state access for monitor / ODT
	u16  reg(int n) const { return m_reg[n].w.l; }
	void set_reg(int n, u16 v) { m_reg[n].w.l = v; }
	u16  psw() const { return m_psw.b.l; }
	void set_psw(u16 v) { m_psw.b.l = u8(v); }
	u16  ppc() const { return m_ppc.w.l; }
	bool halted() const { return m_halted; }
	void set_halted(bool h) { m_halted = h; }
	bool waiting() const { return m_wait_state; }
	u64  insn_count() const { return m_insns; }
	std::function<void(u16 pc)> trace_hook;   // called before each instruction

